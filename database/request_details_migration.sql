USE campusconnect;

ALTER TABLE service_requests
  ADD COLUMN IF NOT EXISTS copies INT NULL,
  ADD COLUMN IF NOT EXISTS print_type VARCHAR(30) NULL,
  ADD COLUMN IF NOT EXISTS paper_size VARCHAR(20) NULL,
  ADD COLUMN IF NOT EXISTS sides VARCHAR(30) NULL,
  ADD COLUMN IF NOT EXISTS device_type VARCHAR(100) NULL,
  ADD COLUMN IF NOT EXISTS pickup_location VARCHAR(200) NULL,
  ADD COLUMN IF NOT EXISTS drop_location VARCHAR(200) NULL,
  ADD COLUMN IF NOT EXISTS travel_date DATE NULL,
  ADD COLUMN IF NOT EXISTS travel_time TIME NULL,
  ADD COLUMN IF NOT EXISTS people_count INT NULL,
  ADD COLUMN IF NOT EXISTS special_requirements TEXT NULL;

CREATE TABLE IF NOT EXISTS request_attachments (
  id INT AUTO_INCREMENT PRIMARY KEY,
  request_id INT NOT NULL,
  file_name VARCHAR(255) NOT NULL,
  file_url VARCHAR(500) NOT NULL,
  mime_type VARCHAR(100) NOT NULL,
  file_size INT NOT NULL,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (request_id) REFERENCES service_requests(id) ON DELETE CASCADE
);
